create function private.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger app_users_set_updated_at before update on public.app_users for each row execute function private.set_updated_at();
create trigger bids_set_updated_at before update on public.bids for each row execute function private.set_updated_at();
create trigger leagues_set_updated_at before update on public.leagues for each row execute function private.set_updated_at();

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'app_users','app_sessions','leagues','league_members','teams','players','player_values',
    'squads','matchdays','lineups','lineup_players','market_listings','bids','transfers',
    'fixtures','player_match_stats','fantasy_scores','chat_messages','notifications','audit_log'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, authenticated', table_name);
    execute format('grant select, insert, update, delete on table public.%I to service_role', table_name);
  end loop;
end $$;

grant usage on schema public to service_role;
grant usage on schema private to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on function private.set_updated_at() from public, anon, authenticated;
grant execute on function private.set_updated_at() to service_role;
